    #[test]
    fn country_known() {
        assert_eq!(country_name("FR"), Some("France"));
        assert_eq!(country_name("US"), Some("United States"));
    }

    #[test]
    fn country_unknown_code_returns_none() {
        assert!(country_name("XX").is_none());
    }

    #[test]
