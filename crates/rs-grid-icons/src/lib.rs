    // ── countries — translated ───────────────────

    #[test]
    fn country_name_in_en_and_unknown_fall_back_to_english() {
        assert_eq!(country_name_in("FR", "en"), country_name("FR"));
        assert_eq!(country_name_in("FR", "xx"), country_name("FR"));
    }

    #[test]
    fn country_name_in_strips_region_subtag() {
        assert_eq!(country_name_in("US", "fr-CA"), country_name_in("US", "fr"));
    }

    #[test]
    fn spot_check_known_translations() {
        assert_eq!(country_name_in("FR", "de"), Some("Frankreich"));
        assert_eq!(country_name_in("US", "fr"), Some("États-Unis"));
        assert_eq!(country_name_in("GB-ENG", "fr"), Some("Angleterre"));
    }

    #[test]
    fn supported_country_langs_matches_expected() {
        let mut langs = supported_country_langs();
        langs.sort();
        assert_eq!(
            langs,
            vec![
                "ar", "de", "es", "fr", "it", "ja", "ko", "nl", "pl", "pt",
                "ru", "tr", "uk", "zh"
            ]
        );
    }

    #[test]
    fn country_translations_no_duplicate_lang_code_pairs() {
        let mut keys: Vec<(&str, &str)> = COUNTRY_TRANSLATIONS
            .iter()
            .map(|&(l, c, _)| (l, c))
            .collect();
        let before = keys.len();
        keys.sort();
        keys.dedup();
        assert_eq!(before, keys.len(), "duplicate (lang, code) pair");
    }

    // Bypasses the English fallback deliberately — this is the
    // test that actually catches an incomplete CLDR extraction
    // (country_name_in's fallback would otherwise mask a gap).
    #[test]
    fn every_declared_lang_covers_every_flag_code() {
        for lang in supported_country_langs() {
            for (code, _) in all_flags() {
                let has_direct_entry = COUNTRY_TRANSLATIONS
                    .binary_search_by(|&(l, c, _)| (l, c).cmp(&(lang, code)))
                    .is_ok();
                assert!(has_direct_entry, "{lang}: no direct entry for {code}");
            }
        }
    }

    #[test]
    fn most_flags_have_distinct_uris() {
        // A few territories may share the exact same SVG,
        // but the vast majority must be unique.
        let uris: Vec<&str> = all_flags().map(|(_, v)| v).collect();
        let mut sorted = uris.clone();
        sorted.sort();
        sorted.dedup();
        let duplicates = uris.len() - sorted.len();
        assert!(
            duplicates <= 10,
            "too many duplicate flag URIs: {duplicates}"
        );
    }
